<?php

declare(strict_types=1);

/**
 * Copies the Mulla PHP SDK into vendor-prefixed/ under the MullaPayments\Vendor\ namespace.
 *
 * WordPress loads every plugin into one PHP process. Prefixing guarantees this plugin's copy
 * of the SDK never collides with another plugin (or a theme) that bundles a different version.
 * Runs automatically after `composer install/update`.
 *
 * Code is rewritten with PHP's tokenizer (namespaces, imports, qualified names); doc comments
 * are rewritten too, so static analysis sees the prefixed types.
 */

const SOURCE_PACKAGE = 'kayko/mulla-php';
const ORIGINAL_NAMESPACE = 'Mulla';
const PREFIX = 'MullaPayments\\Vendor\\';

$root = dirname(__DIR__);
$source = $root . '/vendor/' . SOURCE_PACKAGE . '/src';
$target = $root . '/vendor-prefixed/' . SOURCE_PACKAGE . '/src';

if (!is_dir($source)) {
    fwrite(STDERR, "prefix-sdk: {$source} not found. Run composer install first.\n");
    exit(1);
}

removeDirectory($root . '/vendor-prefixed');

$count = 0;
$iterator = new RecursiveIteratorIterator(new RecursiveDirectoryIterator($source, FilesystemIterator::SKIP_DOTS));
foreach ($iterator as $file) {
    /** @var SplFileInfo $file */
    $relative = substr($file->getPathname(), strlen($source) + 1);
    $destination = $target . '/' . str_replace('\\', '/', $relative);
    if (!is_dir(dirname($destination)) && !mkdir(dirname($destination), 0777, true) && !is_dir(dirname($destination))) {
        fwrite(STDERR, 'prefix-sdk: cannot create ' . dirname($destination) . "\n");
        exit(1);
    }

    $contents = (string) file_get_contents($file->getPathname());
    file_put_contents($destination, $file->getExtension() === 'php' ? prefix($contents) : $contents);
    $count++;
}

copy($root . '/vendor/' . SOURCE_PACKAGE . '/LICENSE', $root . '/vendor-prefixed/' . SOURCE_PACKAGE . '/LICENSE');
file_put_contents($root . '/vendor-prefixed/autoload.php', autoloader());

echo "prefix-sdk: prefixed {$count} files from " . SOURCE_PACKAGE . ' into vendor-prefixed/ (' . PREFIX . ORIGINAL_NAMESPACE . ")\n";

function prefix(string $code): string
{
    $out = '';
    $afterNamespaceKeyword = false;

    foreach (token_get_all($code) as $token) {
        if (!is_array($token)) {
            $out .= $token;
            $afterNamespaceKeyword = false;
            continue;
        }

        [$id, $text] = $token;

        if ($id === T_NAMESPACE) {
            $afterNamespaceKeyword = true;
            $out .= $text;
            continue;
        }
        if ($id === T_WHITESPACE) {
            $out .= $text;
            continue;
        }

        $out .= match (true) {
            $id === T_NAME_QUALIFIED && str_starts_with($text, ORIGINAL_NAMESPACE . '\\') => PREFIX . $text,
            $id === T_NAME_FULLY_QUALIFIED && str_starts_with($text, '\\' . ORIGINAL_NAMESPACE . '\\') => '\\' . PREFIX . substr($text, 1),
            $id === T_STRING && $afterNamespaceKeyword && $text === ORIGINAL_NAMESPACE => PREFIX . $text,
            $id === T_DOC_COMMENT || $id === T_COMMENT => (string) preg_replace(
                '/(?<![\w\\\\])(\\\\?)' . ORIGINAL_NAMESPACE . '\\\\/',
                '$1' . str_replace('\\', '\\\\', PREFIX) . ORIGINAL_NAMESPACE . '\\\\',
                $text,
            ),
            default => $text,
        };
        $afterNamespaceKeyword = false;
    }

    return $out;
}

function autoloader(): string
{
    $prefix = var_export(PREFIX . ORIGINAL_NAMESPACE . '\\', true);
    $dir = var_export('/' . SOURCE_PACKAGE . '/src/', true);

    return <<<PHP
        <?php

        // Generated by bin/prefix-sdk.php. Do not edit.

        spl_autoload_register(static function (string \$class): void {
            \$prefix = {$prefix};
            if (strncmp(\$class, \$prefix, strlen(\$prefix)) !== 0) {
                return;
            }
            \$file = __DIR__ . {$dir} . str_replace('\\\\', '/', substr(\$class, strlen(\$prefix))) . '.php';
            if (is_file(\$file)) {
                require \$file;
            }
        });

        PHP;
}

function removeDirectory(string $dir): void
{
    if (!is_dir($dir)) {
        return;
    }
    $items = new RecursiveIteratorIterator(
        new RecursiveDirectoryIterator($dir, FilesystemIterator::SKIP_DOTS),
        RecursiveIteratorIterator::CHILD_FIRST,
    );
    foreach ($items as $item) {
        $item->isDir() ? rmdir($item->getPathname()) : unlink($item->getPathname());
    }
    rmdir($dir);
}
